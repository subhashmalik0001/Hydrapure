// Derived counts
export function getStationCounts(stationList: WaterStation[]) {
  return {
    total: stationList.length,
    safe: stationList.filter(s => s.status === 'SAFE').length,
    caution: stationList.filter(s => s.status === 'CAUTION').length,
    blocked: stationList.filter(s => s.status === 'BLOCKED').length,
  }
}

export function getStationById(stationList: WaterStation[], id: string): WaterStation | undefined {
  return stationList.find(s => s.id === id || s.stationId === id)
}
